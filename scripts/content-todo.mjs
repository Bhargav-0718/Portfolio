/**
 * Collects every `todo:` item and every non-verified status from content/
 * into CONTENT-TODO.md, so missing information is tracked in one place.
 *
 *   npm run content:todo
 */
import fs from "node:fs";
import path from "node:path";
import matter from "gray-matter";

const root = path.resolve(import.meta.dirname, "..");
const contentDir = path.join(root, "content");
const collections = ["cases", "leadership", "curiosity", "field-notes"];

const sections = [];
let total = 0;

for (const collection of collections) {
  const dir = path.join(contentDir, collection);
  if (!fs.existsSync(dir)) continue;

  const rows = fs
    .readdirSync(dir)
    .filter((f) => /\.mdx?$/.test(f))
    .map((file) => ({ file, data: matter(fs.readFileSync(path.join(dir, file), "utf8")).data }))
    .filter(({ data }) => (data.todo?.length ?? 0) > 0 || (data.status && data.status !== "verified"))
    .sort((a, b) => String(a.data.id).localeCompare(String(b.data.id)));

  if (rows.length === 0) continue;

  const lines = [`## ${collection}`, ""];
  for (const { file, data } of rows) {
    const flags = [data.status ?? "verified", data.draft ? "draft (hidden in production)" : null]
      .filter(Boolean)
      .join(" · ");
    lines.push(`### ${data.id} — ${data.title}`, "", `\`content/${collection}/${file}\` · ${flags}`, "");
    for (const item of data.todo ?? []) {
      lines.push(`- [ ] ${item}`);
      total++;
    }
    lines.push("");
  }
  sections.push(lines.join("\n"));
}

const output = [
  "# Content to-do",
  "",
  "Generated by `npm run content:todo` from the `todo:` and `status:` fields in `content/`.",
  "Do not edit by hand — edit the content files and re-run the script.",
  "",
  `**${total} open items.**`,
  "",
  ...sections,
].join("\n");

fs.writeFileSync(path.join(root, "CONTENT-TODO.md"), output);
console.log(`CONTENT-TODO.md written · ${total} open items`);
